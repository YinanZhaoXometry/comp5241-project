function versionLineOf(item: ApprovalItem): string {
  return `version id: ${item.versionId} · ${item.lessonCount} lessons · content hash ${item.hash}…`;
}

function QueueStatusPill({ status }: { status: ApprovalStatus }) {
  if (status === "approved") {
    return (
      <span className={kit.pillSuccess}>
        <span className={kit.dot} />
        Approved
      </span>
    );
  }
  return (
    <span className={kit.pillWarn}>
      <span className={kit.dot} />
      {status === "changes" ? "Changes requested" : "Pending"}
    </span>
  );
}

function DiffStatePill({ state }: { state: DiffState }) {
  if (state === "added") {
    return (
      <span className={kit.pillSuccess}>
        <span className={kit.dot} />
        Added lesson
      </span>
    );
  }
  if (state === "edited") {
    return (
      <span className={kit.pillWarn}>
        <span className={kit.dot} />
        Edited section
      </span>
    );
  }
  return (
    <span className={kit.pillMuted}>
      <span className={kit.dot} />
      Unchanged
    </span>
  );
}

/* ── screen ───────────────────────────────────────────────────────────── */

type DialogKind = "approve" | "request";

export function InstructorApprovals() {
  const [items, setItems] = useState<readonly ApprovalItem[]>(INITIAL_ITEMS);
  const [selectedId, setSelectedId] = useState<string>(INITIAL_ITEMS[0].id);
  const [openDiffs, setOpenDiffs] = useState<Record<string, boolean>>({});
  const [dialog, setDialog] = useState<DialogKind | null>(null);
  const [requestNote, setRequestNote] = useState("");

  const approveBtnRef = useRef<HTMLButtonElement>(null);
  const requestBtnRef = useRef<HTMLButtonElement>(null);
  const detailRef = useRef<HTMLDivElement | null>(null);

  const selected = items.find(item => item.id === selectedId);

  const counts = { added: 0, edited: 0, unchanged: 0 };
  if (selected) {
    for (const entry of selected.diff) counts[entry.state] += 1;
  }

  function selectItem(id: string) {
    setSelectedId(id);
    setOpenDiffs({});
  }

  function confirmApprove() {
    const item = items.find(candidate => candidate.id === selectedId);
    setDialog(null);
    if (!item || item.status !== "pending") return;
    setItems(prev =>
      prev.map(candidate =>
        candidate.id === item.id ? { ...candidate, status: "approved" as const, decidedOn: "just now" } : candidate,
      ),
    );
  }

  function confirmRequest() {
    const item = items.find(candidate => candidate.id === selectedId);
    const note = requestNote.trim();
    setDialog(null);
    if (!item || item.status !== "pending" || note.length === 0) return;
    setItems(prev =>
      prev.map(candidate =>
        candidate.id === item.id ? { ...candidate, status: "changes" as const, requestNote: note } : candidate,
      ),
    );
  }

  return (
    <div className={st.screen}>
      <div className={st.pageHead}>
        <div>
          <h1 className={st.title}>Approvals</h1>
          <p className={st.sub}>
            Nothing reaches students until you approve an exact version — identified by its version id and content hash,
            not just a course name. Review the lesson-by-lesson diff, then approve or request changes.
          </p>
        </div>
      </div>

      <div className={st.approvalsGrid}>
        <section aria-labelledby="queue-h">
          <h2 id="queue-h" className={st.listLabel}>
            Queue
          </h2>
          <fieldset className={st.queueFieldset}>
            <legend className={st.srOnly}>Pending and decided approvals</legend>
            <div className={st.queueList}>
              {items.map(item => (
                <button
                  key={item.id}
                  type="button"
                  className={st.queueItem}
                  aria-pressed={item.id === selectedId}
                  onClick={() => selectItem(item.id)}
                >
                  <span className={st.qTop}>
                    <span className={st.qName}>
                      {item.course}
                      <span className={st.verChip}>{item.version}</span>
                    </span>
                    <QueueStatusPill status={item.status} />
                  </span>
                  <span className={st.qChanged}>{item.changed}</span>
                  <span className={st.qBy}>
                    {item.by} · {item.when}
                  </span>
                </button>
              ))}
            </div>
          </fieldset>
        </section>

        {selected && (
          <section ref={detailRef} tabIndex={-1} className={st.detail} aria-labelledby="detail-title" aria-live="polite">
            <h2 id="detail-title" className={st.detailTitle}>
              {selected.course} — {selected.version}
            </h2>
            <p className={st.dBy}>
              {selected.by} · {selected.when}
            </p>
            <div className={st.versionLine}>{versionLineOf(selected)}</div>
            <p className={st.dStateNote}>
              Diff against the version students currently see: {counts.added} added · {counts.edited} edited ·{" "}
              {counts.unchanged} unchanged.
            </p>
            <p className={st.diffTitle}>Lesson-by-lesson diff</p>
            <div className={st.diffList}>
              {selected.diff.map(entry => {
                const key = `${selected.id}-${entry.n}`;
                const open = openDiffs[key] === true;
                return (
                  <div key={key} className={st.diffRow}>
                    <div className={st.diffRowMain}>
                      <span className={st.lessonNum}>{entry.n}</span>
                      <span className={st.lessonName}>
                        {entry.title}
                        {entry.sub ? <span className={st.lessonSub}>{entry.sub}</span> : null}
                      </span>
                      <DiffStatePill state={entry.state} />
                      {entry.state === "edited" && (
                        <button
                          type="button"
                          className={st.diffToggle}
                          aria-expanded={open}
                          aria-controls={`diff-change-${key}`}
                          onClick={() => setOpenDiffs(prev => ({ ...prev, [key]: !open }))}
                        >
                          {open ? "Hide change" : "View change"}
                        </button>
                      )}
                    </div>
                    {entry.state === "edited" && open && (
                      <div className={st.diffChange} id={`diff-change-${key}`}>
                        <div className={st.beforeAfter}>
                          <div className={st.baBlock}>
                            <span className={st.baLabel}>Before · currently live text</span>
                            <p className={st.baText}>{entry.before}</p>
                          </div>
                          <div className={`${st.baBlock} ${st.baAfter}`}>
                            <span className={st.baLabel}>After · in {selected.version}</span>
                            <p className={st.baText}>{entry.after}</p>
                          </div>
                        </div>
                      </div>
                    )}
                  </div>
                );
              })}
            </div>
            {selected.status === "pending" ? (
              <div className={st.detailActions}>
                <button ref={approveBtnRef} type="button" className={st.primaryBtn} onClick={() => setDialog("approve")}>
                  Approve this exact version
                </button>
                <button
                  ref={requestBtnRef}
                  type="button"
                  className={st.secondaryBtn}
                  onClick={() => {
                    setRequestNote("");
                    setDialog("request");
                  }}
                >
                  Request changes
                </button>
              </div>
            ) : selected.status === "approved" ? (
              <output className={`${st.decisionNote} ${st.decisionApproved}`}>
                <span className={st.noteLabel}>Approved · {selected.decidedOn ?? selected.when}</span>
                Students will see exactly this version. Any further edit creates a new version that needs its own
                approval.
              </output>
            ) : (
              <output className={`${st.decisionNote} ${st.decisionChanges}`}>
                <span className={st.noteLabel}>Changes requested</span>
                {selected.requestNote ? `Your note: “${selected.requestNote}” ` : ""}
                This version stays unpublished. A revised version will appear in this queue as a new item.
              </output>
            )}
          </section>
        )}
      </div>

      <p className={`${st.honestyNote} ${st.pageHonesty}`}>
        Sample prototype — approving or requesting changes updates only this screen. In a live system an approval
        publishes the exact version shown, and the content hash lets anyone confirm students received it unchanged.
      </p>

      {dialog === "approve" && selected && (
        <DialogFrame
          labelId="dlg-approve-title"
          onClose={() => setDialog(null)}
          returnFocusTo={approveBtnRef}
          fallbackFocusTo={detailRef}
        >
          <div className={st.dlgHead}>
            <h2 id="dlg-approve-title" className={st.dlgTitle}>
              Approve this exact version?
            </h2>
          </div>
          <div className={st.dlgBody}>
            <p>
              Approval is version-exact. <strong>Students will see exactly this version</strong> — the lessons and text
              you just reviewed, byte for byte. Any later edit creates a new version that needs its own approval.
            </p>
            <div className={st.dlgVersion}>{versionLineOf(selected)}</div>
            <div className={st.honestyNote}>
              Sample — nothing is published; the queue on this screen updates to show the decision.
            </div>
          </div>
          <div className={st.dlgFoot}>
            <button type="button" className={st.quietBtn} onClick={() => setDialog(null)}>
              Go back
            </button>
            <button type="button" className={st.secondaryBtn} onClick={confirmApprove}>
              Approve this exact version
            </button>
          </div>
        </DialogFrame>
      )}

      {dialog === "request" && selected && (
        <DialogFrame
          labelId="dlg-request-title"
          onClose={() => setDialog(null)}
          returnFocusTo={requestBtnRef}
          fallbackFocusTo={detailRef}
        >
          <div className={st.dlgHead}>
            <h2 id="dlg-request-title" className={st.dlgTitle}>
              Request changes
            </h2>
          </div>
          <div className={st.dlgBody}>
            <p>Explain what needs to change. The version stays unpublished until a revised version is approved.</p>
            <div className={st.dlgVersion}>{versionLineOf(selected)}</div>
            <div className={st.dlgField}>
              <label htmlFor="request-note">Note for the revision</label>
              <textarea
                id="request-note"
                className={kit.textarea}
                placeholder="e.g. Lesson 3's new sample-size explanation drops the worked example — keep both."
                value={requestNote}
                onChange={event => setRequestNote(event.target.value)}
              />
            </div>
          </div>
          <div className={st.dlgFoot}>
            <button type="button" className={st.quietBtn} onClick={() => setDialog(null)}>
              Cancel
            </button>
            <button
              type="button"
              className={st.secondaryBtn}
              disabled={requestNote.trim().length === 0}
              onClick={confirmRequest}
            >
              Send change request
            </button>
          </div>
        </DialogFrame>
      )}
    </div>
  );
}
